"""Gymnasium Env API conformance, tutorial-style wrappers and the training benchmark."""

import json
import sys
from pathlib import Path

from auditenv.env import AuditEnv
from auditenv.env.checker import check_env
from auditenv.wrappers import OPTIONS, AuditOptionsEnv, RecordEpisodeStatistics

ROOT = Path(__file__).resolve().parents[1]


def test_check_env_passes(tmp_path):
    passed = check_env(lambda render_mode=None: AuditEnv(workdir=tmp_path, render_mode=render_mode))
    assert len(passed) >= 8


def test_np_random_seed_and_reset_info(tmp_path):
    env = AuditEnv(workdir=tmp_path)
    assert env.np_random_seed == -1
    _, info = env.reset(seed=77)
    assert env.np_random_seed == 77 and info["steps_used"] == 0
    import random
    assert isinstance(env.np_random, random.Random)


def test_record_episode_statistics_like_gymnasium(episodes):
    env = RecordEpisodeStatistics(AuditEnv(mode="train"), buffer_length=5)
    for ep in episodes["clean"]:
        env.reset(episode_dir=ep)
        env.step({"tool": "calculator", "args": {"expression": "1"}})
        _, r, term, trunc, info = env.step({"tool": "submit", "args": {"findings": {
            "episode_id": env.unwrapped.episode_id, "findings": []}}})
        assert term and set(info["episode"]) == {"r", "l", "t"} and info["episode"]["l"] == 2
        assert info["episode"]["r"] == r
    assert len(env.return_queue) == len(env.length_queue) == len(env.time_queue) == 2
    assert env.get_wrapper_attr("mode") == "train" and env.unwrapped.__class__ is AuditEnv


def test_options_action_mask_and_invalid_option_cost(episodes):
    ep = episodes["dirty"][0]
    env = AuditOptionsEnv(AuditEnv(mode="train"), mask=False)
    state, info = env.reset(episode_dir=ep)
    mask = dict(zip(OPTIONS, info["action_mask"]))
    assert mask["read_ledger"] == 1 and mask["check_fx"] == 0 and mask["submit"] == 1
    _, _, _, _, info = env.step(OPTIONS.index("check_fx"))   # invalid: wastes exactly one env step
    assert info["inner_steps"] == 1 and info["steps_used"] == 1
    _, _, _, _, info = env.step(OPTIONS.index("read_invoices"))
    assert dict(zip(OPTIONS, info["action_mask"]))["read_invoices"] == 0
    assert dict(zip(OPTIONS, info["action_mask"]))["check_duplicates"] == 1


def test_public_records_alone_solve_every_open_episode(episodes):
    """Solvability: a scripted run of all skills (no access to truth) finds every issue."""
    for ep in episodes["dirty"] + episodes["clean"]:
        env = AuditOptionsEnv(AuditEnv(mode="train"))
        env.reset(episode_dir=ep)
        for a in range(len(OPTIONS)):
            _, reward, term, trunc, info = env.step(a)
            if term or trunc:
                break
        assert term and info["metrics"]["f1"] == 1.0, ep.name


# The two smoke runs below check the protocol and the shape of the results, not learning quality
# (that is the full run's job, artifacts/training.json). Their sizes are cut further than --quick so
# the official container check stays short: they were 50 of 145 s of the suite on one machine.
SMOKE_SWEEP = {"lr": [0.1, 0.4], "episodes": [4, 8], "final_eps": [0.05, 0.1], "gamma": [0.99, 1.0],
               "seeds": [0], "verify_seeds": [0], "n_train": 6, "n_val": 3}


def test_hparam_sweep_quick_uses_validation_only(tmp_path, monkeypatch):
    """The sweep tunes on validation seeds only; the held-out range is never generated by it."""
    sys.path.insert(0, str(ROOT / "examples"))
    import sweep_hparams
    monkeypatch.setattr(sweep_hparams, "QUICK", SMOKE_SWEEP)
    out = tmp_path / "sweep"
    assert sweep_hparams.main(["--quick", "--out", str(out), "--workers", "1"]) == 0
    result = json.loads((out / "sweep.json").read_text())
    train_lo, train_hi = result["protocol"]["train_seeds"]
    val_lo, val_hi = result["protocol"]["val_seeds"]
    held_lo, held_hi = result["protocol"]["heldout_untouched"]
    ranges = sorted([(train_lo, train_hi), (val_lo, val_hi), (held_lo, held_hi)])
    assert all(a[1] < b[0] for a, b in zip(ranges, ranges[1:])), ranges
    assert set(result["best"]) >= {"learning_rate", "episodes", "final_epsilon", "val_return"}
    assert {c["lr"] for c in result["stage1"]} == set(result["grid"]["lr"])
    assert sorted(p.name for p in (out / "pool").iterdir()) == ["train", "val"]


def test_benchstats_bootstrap_is_deterministic_and_sane():
    from auditenv.benchstats import bootstrap_ci, paired_bootstrap, recall_by_type
    vals = [0.1 * (i % 7) - 0.2 for i in range(50)]
    lo, hi = bootstrap_ci(vals, seed="t")
    assert bootstrap_ci(vals, seed="t") == [lo, hi]
    assert lo <= sum(vals) / len(vals) <= hi
    assert bootstrap_ci([0.5] * 10) == [0.5, 0.5]
    better = [v + 0.3 for v in vals]
    up = paired_bootstrap(better, vals)
    assert up["diff"] == 0.3 and up["ci"][0] > 0 and up["p_le_0"] == 0.0 and up["wins"] == 50
    down = paired_bootstrap(vals, better)
    assert down["ci"][1] < 0 and down["p_le_0"] == 1.0 and down["losses"] == 50
    rows = [{"diagnostics": {"by_type": {"fx_conversion": {"tp": 1, "fn": 1}}}},
            {"diagnostics": {"by_type": {"fx_conversion": {"tp": 2, "fn": 0}, "period_cutoff": {"tp": 0, "fn": 0}}}}]
    assert recall_by_type(rows) == {"fx_conversion": 0.75, "period_cutoff": None}


def test_training_results_carry_heldout_statistics(tmp_path, monkeypatch):
    sys.path.insert(0, str(ROOT / "examples"))
    import train_q_learning
    monkeypatch.setattr(train_q_learning, "QUICK", (8, 8, 8, [0, 1]))  # 8 eval episodes cover all 3 classes
    out = tmp_path / "train"
    assert train_q_learning.main(["--quick", "--out", str(out)]) == 0
    res = json.loads((out / "results.json").read_text())
    assert set(res["protocol"]["eval_composition"]) == {"clean", "interacting", "standard"}
    for name in ("q_masked", "q_unmasked", "reconcile", "oracle", "untrained"):
        st = res["stats"][name]
        assert st["ci95"][0] <= st["return"] <= st["ci95"][1], name
        assert set(st["by_class"]) == {"clean", "interacting", "standard"}
    assert res["stats"]["oracle"]["ci95"] == [1.0, 1.0]
    assert {c["b"] for c in res["significance"]} >= {"untrained", "reconcile", "q_unmasked"}
    assert "_rows" not in json.dumps(res) and "_per_episode" not in json.dumps(res)


def test_training_hyperparameters_are_the_ones_the_sweep_chose():
    """README/DESIGN say the hyperparameters come from the validation sweep: keep that claim true."""
    sweep = ROOT / "artifacts" / "sweep.json"
    if not sweep.exists():
        return
    sys.path.insert(0, str(ROOT / "examples"))
    import train_q_learning
    best = json.loads(sweep.read_text())["best"]
    assert train_q_learning.LEARNING_RATE == best["learning_rate"]
    assert train_q_learning.EPISODES_PER_RUN == best["episodes"]
    assert train_q_learning.FINAL_EPSILON == best["final_epsilon"]
    assert train_q_learning.DISCOUNT_FACTOR == best.get("discount_factor", 1.0)
